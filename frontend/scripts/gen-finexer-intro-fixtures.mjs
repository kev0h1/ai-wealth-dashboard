// Regenerates app/design/finexer-consent-intro/brand.generated.ts from the
// shipped brand files in backend/app/data/finexer_brand (G226). Run after
// editing any of them; check:finexer-intro fails if the output is stale.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const BRAND = path.resolve(here, "../../backend/app/data/finexer_brand");
const OUT = path.resolve(here, "../app/design/finexer-consent-intro/brand.generated.ts");

// Mirrors backend/scripts/finexer_template.py minify_css.
export function minifyCss(css) {
  css = css.replace(/\/\*[\s\S]*?\*\//g, "");
  css = css.replace(/\s+/g, " ");
  css = css.replace(/\s*([{};:,>])\s*/g, "$1");
  return css.trim().replaceAll(";}", "}");
}
export const read = (...p) => fs.readFileSync(path.join(BRAND, ...p), "utf8");
// The variants replace the existing .sorted-intro rules in sorted.css.
export function sharedWithoutOldIntro() {
  return read("sorted.css").replace(/\/\* Our own intro block[\s\S]*?\.sorted-intro p \{[^}]*\}\n/, "");
}
export function build() {
  const data = {
    tokens: { light: read("sorted-light.css"), dark: read("sorted-dark.css") },
    shared: read("sorted.css"),
    sharedWithoutOldIntro: sharedWithoutOldIntro(),
    today: read("header.html").trim(),
    variants: Object.fromEntries(
      ["a", "b", "c"].map((v) => [v, { html: read("intro", `${v}.html`).trim(), css: read("intro", `${v}.css`) }]),
    ),
  };
  return `// GENERATED by scripts/gen-finexer-intro-fixtures.mjs, do not edit.\nexport const BRAND = ${JSON.stringify(data, null, 2)} as const;\n`;
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  fs.writeFileSync(OUT, build());
  console.log("wrote", OUT);
}
